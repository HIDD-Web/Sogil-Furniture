export function translate(lang, key) {
  const parts = key.split(".");
  let cur = dict[lang] || dict.id;
  for (const p of parts) {
    cur = cur?.[p];
    if (cur == null) break;
  }
  if (cur == null) {
    cur = dict.id;
    for (const p of parts) cur = cur?.[p];
  }
  return cur == null ? key : cur;
}
